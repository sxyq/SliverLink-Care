interface ApiMessagePayload {
  message?: unknown;
  messageKey?: unknown;
  error?: unknown;
}

export interface ResolvedApiMessage {
  message: string;
  messageKey?: string;
}

export class ApiMessageError extends Error {
  readonly messageKey?: string;

  constructor(message: string, messageKey?: string) {
    super(message);
    this.name = 'ApiMessageError';
    this.messageKey = messageKey;
  }
}

function nonEmptyString(value: unknown): string | undefined {
  return typeof value === 'string' && value.trim() ? value : undefined;
}

function isSafeLegacyPlainMessage(value: string): boolean {
  const trimmed = value.trim();
  if (!trimmed || trimmed.length > 160 || /[\r\n]/.test(trimmed)) return false;
  if (/^<!doctype\b|<\/?[a-z][^>]*>/i.test(trimmed)) return false;
  if (/^[{\[]/.test(trimmed)) return false;

  return !/\b(?:upstream|proxy|gateway|nginx|cloudflare|stack(?:\s*trace)?|exception|traceback|request\s*id|java\.|org\.|com\.|errno|econn\w*|socket|connection\s+(?:reset|refused|timed?\s*out)|internal\s+server\s+error|bad\s+gateway|service\s+unavailable)\b|\bat\s+\S+\([^)]*:\d+\)/i.test(trimmed);
}

function normalizeApiMessagePayload(payload: unknown): ApiMessagePayload {
  if (typeof payload === 'string') {
    const trimmed = payload.trim();
    if (!trimmed) return {};

    try {
      const parsed = JSON.parse(trimmed) as unknown;
      if (typeof parsed === 'string') return { message: parsed };
      return parsed && typeof parsed === 'object' ? parsed as ApiMessagePayload : {};
    } catch {
      return isSafeLegacyPlainMessage(payload) ? { message: payload } : {};
    }
  }

  return payload && typeof payload === 'object' ? payload as ApiMessagePayload : {};
}

export function resolveApiMessage(
  payload: unknown,
  translate: (key: string, params?: MessageParams) => string,
  fallbackKey = 'errors.requestFailed',
): ResolvedApiMessage {
  const normalized = normalizeApiMessagePayload(payload);
  const messageKey = nonEmptyString(normalized.messageKey);

  if (messageKey) {
    const localized = translate(messageKey);
    if (nonEmptyString(localized) && localized !== messageKey) {
      return { message: localized, messageKey };
    }
  }

  const serverMessage = nonEmptyString(normalized.message) || nonEmptyString(normalized.error);
  if (serverMessage) return { message: serverMessage, messageKey };

  const fallback = translate(fallbackKey);
  const chineseFallback = readMessage(messages['zh-CN'], fallbackKey);
  return {
    message: nonEmptyString(fallback) && fallback !== fallbackKey
      ? fallback
      : chineseFallback || fallbackKey,
    messageKey,
  };
}

export function getErrorMessage(error: unknown, translate: (key: string, params?: MessageParams) => string, fallbackKey: string): string {
  if (error instanceof ApiMessageError) {
    return resolveApiMessage(error, translate, fallbackKey).message;
  }
  if (error instanceof Error && nonEmptyString(error.message)) return error.message;
  return resolveApiMessage(undefined, translate, fallbackKey).message;
}

export function createI18nRuntime(storage: LocaleStorage) {
  let storedLocale: string | null = null;
  try {
    storedLocale = storage.getItem(LOCALE_STORAGE_KEY);
  } catch {
    // Storage can be unavailable in private browsing and restricted WebViews.
  }
  let locale: Locale = isSupportedLocale(storedLocale) ? storedLocale : 'zh-CN';

  return {
    t(key: string, params?: MessageParams): string {
      const value = readMessage(messages[locale], key) || readMessage(messages['zh-CN'], key);
      return interpolate(value || key, params);
    },
    setLocale(nextLocale: Locale) {
      locale = isSupportedLocale(nextLocale) ? nextLocale : 'zh-CN';
      try {
        storage.setItem(LOCALE_STORAGE_KEY, locale);
      } catch {
        // Keep the in-memory locale usable when persistence is unavailable.
      }
    },
    getLocale() {
      return locale;
    },
    getDirection(nextLocale: Locale = locale) {
      return getDirection(nextLocale);
    },
  };
}

export function getMessageKeys(tree: MessageTree = messages['zh-CN'], prefix = ''): string[] {
  return Object.entries(tree).flatMap(([key, value]) => {
    const next = prefix ? `${prefix}.${key}` : key;
    return typeof value === 'string' ? [next] : getMessageKeys(value, next);
  });
}
